"use client";

import { useState } from "react";
import { Icon } from "@/components/Icons";
import { useStore } from "@/components/app/DemoStore";
import { btnDark, btnLight, Card, CardHead, Pill } from "@/components/app/ui";
import {
  billingPeriod,
  changeKind,
  SEED_INVOICES,
  withGst,
  type Invoice,
} from "@/lib/billing";
import { PLANS, type PlanName } from "@/lib/demo-data";
import { todayISO } from "@/lib/format";
import { billablePeople, gstOn, planBlocker } from "@/lib/usage";
import { PlanChangeDialog } from "./PlanChangeDialog";

const money = (n: number) =>
  `${n < 0 ? "−" : ""}A$${Math.abs(n).toLocaleString("en-AU", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const longDate = (iso: string) =>
  new Date(`${iso}T00:00:00`).toLocaleDateString("en-AU", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });

const isoOf = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

export function BillingSection() {
  const {
    ready,
    settings,
    members,
    setPlan,
    upgradePlan,
    scheduleDowngrade,
    cancelPlanChange,
  } = useStore();
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");
  const [target, setTarget] = useState<PlanName | null>(null);

  const today = ready ? todayISO() : "";
  const current = PLANS[settings.plan];
  const trial = !!settings.trialEnds && !!today && settings.trialEnds >= today;
  const pending = settings.pendingPlan;
  const invoices = settings.invoices ?? SEED_INVOICES;
  const renews = ready ? isoOf(billingPeriod(new Date()).end) : "";
  const nextPlan = pending ? PLANS[pending.plan] : current;
  const people = billablePeople(members).length;

  const choose = (plan: PlanName) => {
    setNotice("");
    setError("");
    if (plan === settings.plan) return;
    const blocker = planBlocker(plan, members);
    if (blocker)
      return setError(
        `You cannot move to ${plan} yet. ${blocker} Remove people first.`,
      );
    setTarget(plan);
  };

  const done = (text: string) => {
    setTarget(null);
    setNotice(text);
  };

  const download = (inv: Invoice) => {
    const pad = (s: string) => s.padEnd(52, " ");
    const text = [
      "TAX INVOICE (sample, generated by the REAHUB demo)",
      "",
      `Invoice: ${inv.id}`,
      `Date: ${longDate(inv.date)}`,
      `For: ${inv.title}`,
      `Billed to: ${settings.agency.trading}`,
      `ABN: ${settings.agency.abn}`,
      "",
      ...inv.lines.map((l) => `${pad(l.label)}${money(l.amount)}`),
      "",
      `${pad("Subtotal")}${money(inv.subtotal)}`,
      `${pad("GST (10%)")}${money(inv.gst)}`,
      `${pad("Total paid (AUD)")}${money(inv.total)}`,
      "",
      "This is sample data and not a real invoice.",
    ].join("\n");
    const url = URL.createObjectURL(new Blob([text], { type: "text/plain" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = `${inv.id}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {notice && (
        <p
          role="status"
          className="flex items-start gap-2 rounded-xl bg-tint px-4 py-3 text-sm font-semibold"
        >
          <Icon name="check" className="mt-0.5 h-4 w-4 shrink-0" /> {notice}
        </p>
      )}
      {error && (
        <p
          role="alert"
          className="rounded-xl border border-accent/40 bg-accent/10 px-4 py-3 text-sm font-semibold"
        >
          {error}
        </p>
      )}

      <Card>
        <CardHead
          title="Current plan"
          right={
            trial ? (
              <Pill tone="solid">Free trial</Pill>
            ) : (
              <Pill tone="ok">Active</Pill>
            )
          }
        />
        <div className="grid gap-4 p-5 sm:grid-cols-[1fr_auto] sm:items-end">
          <div>
            <p className="font-display text-3xl font-extrabold tracking-tight">
              {settings.plan}
            </p>
            <p className="mt-1 text-sm text-ink-soft">{current.blurb}</p>
            <p className="mt-3 text-sm">
              <span className="font-semibold">A${current.price}</span> a month +{" "}
              {money(gstOn(current.price))} GST ={" "}
              <span className="font-semibold">
                {money(withGst(current.price))}
              </span>
            </p>
            <p className="mt-1 text-xs text-ink-soft">
              Billed monthly in AUD on the 1st. Upgrades start straight away and
              you pay the difference for the rest of the month. Downgrades and
              cancellations start at the next billing date.
            </p>
          </div>
          <div className="text-sm text-ink-soft sm:text-right">
            <p>{trial ? "Trial ends" : "Next invoice"}</p>
            <p className="font-semibold text-ink">
              {trial
                ? longDate(settings.trialEnds!)
                : renews
                  ? longDate(renews)
                  : "..."}
            </p>
            {!trial && renews && (
              <p className="tabular-nums">{money(withGst(nextPlan.price))}</p>
            )}
          </div>
        </div>

        {pending && (
          <div className="flex flex-wrap items-center justify-between gap-3 border-t border-line bg-accent/[0.06] px-5 py-3.5 text-sm">
            <p className="flex items-start gap-2">
              <Icon
                name="calendar"
                className="mt-0.5 h-4 w-4 shrink-0 text-accent"
              />
              <span>
                <strong>
                  Moves to {pending.plan} on {longDate(pending.on)}.
                </strong>{" "}
                You keep {settings.plan} until then.
              </span>
            </p>
            <button
              type="button"
              onClick={() => {
                cancelPlanChange();
                setNotice(`Change cancelled. You stay on ${settings.plan}.`);
              }}
              className={btnLight}
            >
              Keep {settings.plan}
            </button>
          </div>
        )}

        {settings.card && (
          <div className="flex flex-wrap items-center justify-between gap-3 border-t border-line px-5 py-4 text-sm">
            <p className="flex items-center gap-3">
              <span className="rounded-md border border-line bg-bg px-2 py-1 text-xs font-bold">
                {settings.card.brand}
              </span>
              <span>
                Ending {settings.card.last4}, expires {settings.card.exp}
              </span>
            </p>
            <p className="text-xs text-ink-soft">
              {trial
                ? `First charge on ${longDate(settings.trialEnds!)}`
                : "Charged on the 1st of each month"}
            </p>
          </div>
        )}
      </Card>

      <Card>
        <CardHead
          title="Change plan"
          sub="Per agency, never per seat. You see the exact cost before anything changes."
        />
        <div className="grid gap-3 p-5 md:grid-cols-3">
          {(Object.keys(PLANS) as PlanName[]).map((name) => {
            const p = PLANS[name];
            const on = name === settings.plan;
            const booked = pending?.plan === name;
            const up = p.price > current.price;
            return (
              <div
                key={name}
                className={`flex flex-col rounded-2xl border p-4 ${on ? "border-ink bg-accent/[0.08]" : booked ? "border-accent" : "border-line"}`}
              >
                <p className="font-display text-lg font-extrabold">{name}</p>
                <p className="mt-1 text-2xl font-extrabold tabular-nums">
                  A${p.price}
                  <span className="text-xs font-medium text-ink-soft">
                    {" "}
                    /month + GST
                  </span>
                </p>
                <ul className="mt-3 flex-1 space-y-1 text-xs text-ink-soft">
                  <li>Up to {p.people} people</li>
                  <li>As many teams as you need</li>
                  <li>{p.vaultGb} GB document vault</li>
                  <li>
                    {p.queries
                      ? `${p.queries.toLocaleString("en-AU")} assistant queries a month`
                      : "Unlimited assistant queries"}
                  </li>
                </ul>
                <button
                  type="button"
                  onClick={() => choose(name)}
                  disabled={on || booked}
                  className={`${on || booked ? btnLight : btnDark} mt-4 justify-center disabled:opacity-60`}
                >
                  {on
                    ? "Current plan"
                    : booked
                      ? `Starts ${longDate(pending!.on)}`
                      : trial
                        ? `Switch to ${name}`
                        : up
                          ? `Upgrade to ${name}`
                          : `Move to ${name}`}
                </button>
              </div>
            );
          })}
        </div>
        <p className="border-t border-line bg-bg px-5 py-3 text-xs text-ink-soft">
          Outgrown the bands? The Group plan is for multi-office networks and is
          priced with you.
        </p>
      </Card>

      <Card>
        <CardHead title="Invoices" sub="Tax invoices, GST shown separately" />
        {invoices.length === 0 && (
          <p className="px-5 py-8 text-center text-sm text-ink-soft">
            No invoices yet.{" "}
            {trial
              ? `Your first one is issued when the trial ends on ${longDate(settings.trialEnds!)}.`
              : ""}
          </p>
        )}
        <ul className="divide-y divide-line">
          {invoices.map((inv) => (
            <li
              key={inv.id}
              className="flex flex-wrap items-center justify-between gap-3 px-5 py-3.5 text-sm"
            >
              <span>
                <span className="block font-semibold">{inv.title}</span>
                <span className="block text-xs text-ink-soft">
                  {inv.id} · {longDate(inv.date)}
                </span>
              </span>
              <span className="flex items-center gap-3">
                <span className="font-semibold tabular-nums">
                  {money(inv.total)}
                </span>
                <Pill tone="ok">Paid</Pill>
                <button
                  type="button"
                  onClick={() => download(inv)}
                  className="inline-flex items-center gap-1.5 text-xs font-semibold underline"
                >
                  <Icon name="download" className="h-3.5 w-3.5" /> Download
                </button>
              </span>
            </li>
          ))}
        </ul>
      </Card>

      <Card>
        <CardHead title="Payment method" />
        <div className="flex flex-wrap items-center justify-between gap-3 p-5">
          <div>
            <p className="text-sm font-semibold">
              {settings.card
                ? `${settings.card.brand} ending ${settings.card.last4}`
                : "Visa ending 4242"}
            </p>
            <p className="text-xs text-ink-soft">
              Expires {settings.card?.exp ?? "08/28"}. Sample card, not a real
              payment method.
            </p>
          </div>
          <button type="button" disabled className={`${btnLight} opacity-60`}>
            Update card
          </button>
        </div>
        <p className="border-t border-line bg-bg px-5 py-3 text-xs text-ink-soft">
          Card details are handled by the payment provider and are not part of
          this demo.
        </p>
      </Card>

      {target && (
        <PlanChangeDialog
          from={settings.plan}
          to={target}
          kind={changeKind(settings.plan, target, trial)}
          trialEnds={settings.trialEnds}
          card={settings.card ?? { brand: "Visa", last4: "4242" }}
          people={people}
          onClose={() => setTarget(null)}
          onUpgrade={(p) => {
            upgradePlan(p);
            done(
              p.total >= 0.5
                ? `You're on ${p.to} now. ${money(p.total)} was charged for the rest of the month, and the tax invoice is below.`
                : `You're on ${p.to} now. The small difference is added to your next invoice.`,
            );
          }}
          onDowngrade={(on) => {
            scheduleDowngrade(target, isoOf(on));
            done(
              `Booked. You keep ${settings.plan} until the end of the month and move to ${target} on ${longDate(isoOf(on))}.`,
            );
          }}
          onTrialSwitch={() => {
            setPlan(target);
            done(
              `You're on ${target} now. Nothing was charged during your trial.`,
            );
          }}
        />
      )}
    </div>
  );
}
