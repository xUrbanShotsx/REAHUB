"use client";

import { useState } from "react";
import { Icon } from "@/components/Icons";
import { useStore } from "@/components/app/DemoStore";
import { btnDark, btnLight, Card, CardHead, Pill } from "@/components/app/ui";
import { PLANS, type PlanName } from "@/lib/demo-data";
import { gstOn, planBlocker } from "@/lib/usage";

const money = (n: number) =>
  `A$${n.toLocaleString("en-AU", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const INVOICES = [
  { id: "INV-2026-011", period: "November 2026", date: "1 Nov 2026" },
  { id: "INV-2026-010", period: "October 2026", date: "1 Oct 2026" },
  { id: "INV-2026-009", period: "September 2026", date: "1 Sep 2026" },
];

export function BillingSection() {
  const { settings, members, setPlan } = useStore();
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");
  const current = PLANS[settings.plan];

  const choose = (plan: PlanName) => {
    setNotice("");
    const blocker = plan === settings.plan ? null : planBlocker(plan, members);
    if (blocker)
      return setError(
        `You cannot switch to ${plan} yet. ${blocker} Remove people or teams first.`,
      );
    setError("");
    if (plan === settings.plan) return;
    if (
      !window.confirm(
        `Change to the ${plan} plan at A$${PLANS[plan].price} a month + GST?`,
      )
    )
      return;
    setPlan(plan);
    setNotice(
      `You are now on the ${plan} plan. It starts at your next billing date, and nothing is migrated.`,
    );
  };

  const download = (inv: (typeof INVOICES)[number]) => {
    const price = current.price;
    const gst = gstOn(price);
    const text = [
      "TAX INVOICE (sample, generated by the REAHUB demo)",
      "",
      `Invoice: ${inv.id}`,
      `Date: ${inv.date}`,
      `Period: ${inv.period}`,
      `Billed to: ${settings.agency.trading}`,
      `ABN: ${settings.agency.abn}`,
      "",
      `${settings.plan} plan, one month   ${money(price)}`,
      `GST (10%)                      ${money(gst)}`,
      `Total (AUD)                    ${money(price + gst)}`,
      "",
      "This is sample data and not a real invoice.",
    ].join("\n");
    const url = URL.createObjectURL(new Blob([text], { type: "text/plain" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = `${inv.id}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {notice && (
        <p
          role="status"
          className="flex items-center gap-2 rounded-xl bg-tint px-4 py-3 text-sm font-semibold"
        >
          <Icon name="check" className="h-4 w-4" /> {notice}
        </p>
      )}
      {error && (
        <p
          role="alert"
          className="rounded-xl border border-accent/40 bg-accent/10 px-4 py-3 text-sm font-semibold"
        >
          {error}
        </p>
      )}

      <Card>
        <CardHead title="Current plan" right={<Pill tone="ok">Active</Pill>} />
        <div className="grid gap-4 p-5 sm:grid-cols-[1fr_auto] sm:items-end">
          <div>
            <p className="font-display text-3xl font-extrabold tracking-tight">
              {settings.plan}
            </p>
            <p className="mt-1 text-sm text-ink-soft">{current.blurb}</p>
            <p className="mt-3 text-sm">
              <span className="font-semibold">A${current.price}</span> a month +{" "}
              {money(gstOn(current.price))} GST ={" "}
              <span className="font-semibold">
                {money(current.price + gstOn(current.price))}
              </span>
            </p>
            <p className="mt-1 text-xs text-ink-soft">
              Billed monthly in AUD. No lock-in contract. Cancel anytime, and
              access continues to the end of the month you have paid for.
            </p>
          </div>
          <div className="text-sm text-ink-soft sm:text-right">
            <p>Next invoice</p>
            <p className="font-semibold text-ink">1 Dec 2026</p>
          </div>
        </div>
      </Card>

      <Card>
        <CardHead
          title="Change plan"
          sub="Per agency, never per seat. A plan is a limit, not a different system."
        />
        <div className="grid gap-3 p-5 md:grid-cols-3">
          {(Object.keys(PLANS) as PlanName[]).map((name) => {
            const p = PLANS[name];
            const on = name === settings.plan;
            return (
              <div
                key={name}
                className={`flex flex-col rounded-2xl border p-4 ${on ? "border-ink bg-accent/[0.08]" : "border-line"}`}
              >
                <p className="font-display text-lg font-extrabold">{name}</p>
                <p className="mt-1 text-2xl font-extrabold tabular-nums">
                  A${p.price}
                  <span className="text-xs font-medium text-ink-soft">
                    {" "}
                    /month + GST
                  </span>
                </p>
                <ul className="mt-3 flex-1 space-y-1 text-xs text-ink-soft">
                  <li>Up to {p.people} people</li>
                  <li>
                    {p.teams} team{p.teams === 1 ? "" : "s"}
                  </li>
                  <li>{p.vaultGb} GB document vault</li>
                  <li>
                    {p.queries
                      ? `${p.queries.toLocaleString("en-AU")} assistant queries a month`
                      : "Unlimited assistant queries"}
                  </li>
                </ul>
                <button
                  type="button"
                  onClick={() => choose(name)}
                  disabled={on}
                  className={`${on ? btnLight : btnDark} mt-4 justify-center disabled:opacity-60`}
                >
                  {on ? "Current plan" : `Switch to ${name}`}
                </button>
              </div>
            );
          })}
        </div>
        <p className="border-t border-line bg-bg px-5 py-3 text-xs text-ink-soft">
          Outgrown the bands? The Group plan is for multi-office networks and is
          priced with you.
        </p>
      </Card>

      <Card>
        <CardHead title="Invoices" sub="Tax invoices, GST shown separately" />
        <ul className="divide-y divide-line">
          {INVOICES.map((inv) => (
            <li
              key={inv.id}
              className="flex flex-wrap items-center justify-between gap-3 px-5 py-3.5 text-sm"
            >
              <span>
                <span className="block font-semibold">{inv.period}</span>
                <span className="block text-xs text-ink-soft">
                  {inv.id} · {inv.date}
                </span>
              </span>
              <span className="flex items-center gap-3">
                <span className="font-semibold tabular-nums">
                  {money(current.price + gstOn(current.price))}
                </span>
                <Pill tone="ok">Paid</Pill>
                <button
                  type="button"
                  onClick={() => download(inv)}
                  className="inline-flex items-center gap-1.5 text-xs font-semibold underline"
                >
                  <Icon name="download" className="h-3.5 w-3.5" /> Download
                </button>
              </span>
            </li>
          ))}
        </ul>
      </Card>

      <Card>
        <CardHead title="Payment method" />
        <div className="flex flex-wrap items-center justify-between gap-3 p-5">
          <div>
            <p className="text-sm font-semibold">Visa ending 4242</p>
            <p className="text-xs text-ink-soft">
              Expires 08/28. Sample card, not a real payment method.
            </p>
          </div>
          <button type="button" disabled className={`${btnLight} opacity-60`}>
            Update card
          </button>
        </div>
        <p className="border-t border-line bg-bg px-5 py-3 text-xs text-ink-soft">
          Card details are handled by the payment provider and are not part of
          this demo.
        </p>
      </Card>
    </div>
  );
}
